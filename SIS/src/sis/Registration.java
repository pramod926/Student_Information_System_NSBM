    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // Get user inputs
        String email = txtEmail.getText().trim();
        String password = new String(jPasswordField1.getPassword()); // safer than getText()
        String mobile = jTextField3.getText().trim();
        String course_id = jComboBox1.getSelectedItem().toString();

        if (email.isEmpty() || password.isEmpty() || mobile.isEmpty() || course_id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!");
            return;
        }

        Connection con = null;
        PreparedStatement pst = null;

        try {
            // Get DB connection
            con = (Connection) DBConnection.getConnection();

            // SQL insert query
            String sql = "INSERT INTO users(email, password_hash, mobile_number,course_id) VALUES (?, ?, ?, ?)";
            pst = con.prepareStatement(sql);

            // Set parameters
            pst.setString(1, email);
            pst.setString(2, password); // storing plain password (not recommended)
            pst.setString(3, mobile);
            pst.setString(4, course_id);

            // Execute insert
            int rowsAffected = pst.executeUpdate();

            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Registered Successfully!");
                new Login().setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Registration failed!");
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error occurred while registering!");
        } finally {
            // Close resources
            try {
                if (pst != null) {
                    pst.close();
                }
                if (con != null) {
                    con.close();
                }
            } catch (Exception ex) {
                ex.printStackTrace();
            }
        }

    }//GEN-LAST:event_jButton2ActionPerformed

