    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String studentId = jComboBox2.getSelectedItem().toString();
        String courseName = jComboBox1.getSelectedItem().toString();
        String marksText = jTextField4.getText().trim();

        // Validate
        if (studentId.isEmpty() || courseName.isEmpty() || marksText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields.");
            return;
        }

        int marks = 0;
        try {
            marks = Integer.parseInt(marksText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Marks must be a number.");
            return;
        }

        // SQL Queries
        String getCourseIdSql = "SELECT course_id FROM courses WHERE course_name = ?";
        String checkDuplicateSql = "SELECT * FROM exam_results WHERE student_id = ? AND course_id = ?";
        String insertSql = "INSERT INTO exam_results (student_id, course_id, marks) VALUES (?, ?, ?)";

        try (Connection con = DBConnection.getConnection()) {

            int courseId = -1;

            // --- Get Course ID ---
            try (PreparedStatement pst = con.prepareStatement(getCourseIdSql)) {
                pst.setString(1, courseName);
                ResultSet rs = pst.executeQuery();

                if (rs.next()) {
                    courseId = rs.getInt("course_id");
                } else {
                    JOptionPane.showMessageDialog(this, "Course ID not found for selected course!");
                    return;
                }
            }

            // --- Check for Duplicate Entry ---
            try (PreparedStatement pst = con.prepareStatement(checkDuplicateSql)) {
                pst.setInt(1, Integer.parseInt(studentId));
                pst.setInt(2, courseId);

                ResultSet rs = pst.executeQuery();
                if (rs.next()) {
                    JOptionPane.showMessageDialog(this,
                            "Result already exists for this student and subject!");
                    return; // stop here
                }
            }

            // --- Insert Exam Result ---
            try (PreparedStatement pst = con.prepareStatement(insertSql)) {
                pst.setInt(1, Integer.parseInt(studentId));
                pst.setInt(2, courseId);
                pst.setInt(3, marks);

                int rows = pst.executeUpdate();
                if (rows > 0) {
                    JOptionPane.showMessageDialog(this, "Exam Result Added Successfully!");
                    jTextField4.setText("");
                }
            }

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton2ActionPerformed
     
    

